// Prioritize the listener's R&B, soul, blues, pop and mellow-house taste.
// Every YouTube result must earn 100,000 genuine reported views on that video.
export const targetedMixChannels=[
  {channelId:'UC8TZwtZ17WKFJSmwTZQpBTA',name:'My Analog Journal',q:'soul funk R&B vinyl'},
  {channelId:'UCJOtExbMu0RqIdiE4nMUPxQ',name:'The Lot Radio',q:'soul R&B soulful house'},
  {channelId:'UCmfF7JZv26UUKyRedViGIlw',name:'HÖR Berlin',q:'soul funk soulful house'},
  {channelId:'UCQmEioliO9mSfg3VpcMjPoQ',name:'Soulection',q:'soul R&B mix'},
];
export const youtubeMixQueries=[
  'R&B soul vinyl DJ mix',
  '90s RnB neo soul slow jams DJ set',
  'blues soul motown vinyl DJ mix',
  'pop RnB soul eclectic DJ mix',
  'soulful mellow house balearic light house DJ set',
  'My Analog Journal soul funk DJ vinyl mix',
];
const mixTitle=/\b(?:dj\s*(?:set|mix|session)|vinyl\s*(?:mix|set|session|selection)|(?:soul|funk|disco|rhythm|rnb|r&b|blues|pop|house)\s*(?:dj\s*)?(?:mix|playlist|selection|session)|(?:mixtape|mix tape|mixes|playlist)|boiler room|hör berlin|kiosk radio|the lot radio|my analog journal)\b/i;
const notMix=/\b(?:interview|podcast|talk show|reaction|tutorial|how to|review|full album|official music video|visualizer|shorts?|trailer|teaser|single track|remix tutorial|news)\b/i;
const spamTitle=/\b(?:best vintage funk mix|best soul music mix|no copyright music|royalty free|ai generated|generated by ai|relaxing 24\/7|top hits 2026)\b/i;
const credibleCurators=/\b(?:Kiosk Radio|Boiler Room|HÖR Berlin|My Analog Journal|The Lot Radio|Mixmag|Soulection|DJ Mag|DJ HASEBE|R&B ONLY)\b/i;
const genreRules=[
  ['rnb',/\b(?:r\s*&\s*b|rnb|rhythm\s*(?:and|&)\s*blues|slow jams?|new jack swing)\b/i],
  ['light-house',/\b(?:(?:soulful|light|mellow|soft|chill|balearic|deep|organic|laid[ -]?back|funky|disco)[ -]?house|house[ -]?(?:soulful|grooves?|chill|mellow|balearic))\b/i],
  ['soul',/\b(?:neo[ -]?soul|northern soul|soul(?:ful)?|motown)\b/i],
  ['blues',/\b(?:blues|bluesy)\b/i],
  ['pop',/\b(?:indie[ -]?pop|dream[ -]?pop|pop)\b/i],
  ['funk',/\b(?:funk|boogie|disco|groove)\b/i],
];
const durationSeconds=value=>{
  if(typeof value!=='string')return 0;
  const m=value.match(/^P(?:([\d.]+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/);
  return m ? Number(m[1]??0)*86400+Number(m[2]??0)*3600+Number(m[3]??0)*60+Number(m[4]??0) : 0;
};
const videoId=value=>typeof value==='string' && /^[\w-]{11}$/.test(value);
const channelIdValid=value=>typeof value==='string' && /^UC[\w-]{22}$/.test(value);
const youtubeWindowStart=startsOn=>new Date(Date.parse(startsOn)-365*86400000).toISOString().slice(0,10);
const tagsOf=snippet=>Array.isArray(snippet?.tags)?snippet.tags.filter(x=>typeof x==='string').slice(0,40):[];

// Use video-specific titles and tags first, then the video's description.
// Never label a generic Boiler Room/Kiosk upload "soul" solely by its publisher.
export function classifyYouTubeMixStyle(snippet={}) {
  const title=String(snippet.title??'');
  const tags=tagsOf(snippet);
  const description=String(snippet.description??'').slice(0,600);
  const evidence=[title,tags.join(' '),description];
  if(excludesElectronicMix({title,tags,genre:description.slice(0,250)})
    || excludesJazz({format:'Radio show',title,tags,genre:description.slice(0,250)})
    || /\b(?:ai[ -]generated|made with ai|ai assisted music)\b/i.test(description))return;
  for(const text of evidence)for(const [style,pattern] of genreRules)
    if(pattern.test(text))return style;
}

export function verifiedYouTubeMix(video, startsOn, today, channel) {
  const {snippet={},status={},contentDetails={},statistics={}}=video??{};
  const id=video?.id;
  const date=snippet.publishedAt?.slice(0,10),title=snippet.title?.trim();
  const channelId=snippet.channelId,channelTitle=snippet.channelTitle?.trim();
  const length=durationSeconds(contentDetails.duration);
  // Undefined/non-public counts are not accepted; a subscriber count is not
  // proof of popularity for a specific mix.
  const views=statistics.viewCount===undefined?NaN:Number(statistics.viewCount);
  const subscribers=channel?.statistics?.subscriberCount===undefined?NaN:Number(channel.statistics.subscriberCount);
  const targeted=targetedMixChannels.find(x=>x.channelId===channelId);
  const known=!!targeted||credibleCurators.test(channelTitle??'');
  const style=classifyYouTubeMixStyle(snippet);
  const respected=Number.isSafeInteger(views) && Number.isSafeInteger(subscribers)
    && views>=MIN_YOUTUBE_MIX_VIEWS && subscribers>=2500;
  if(!videoId(id)||!channelIdValid(channelId)||channel?.id!==channelId||!isoDate(date)||!title||!channelTitle
    || !isoDate(startsOn)||!isoDate(today)||date<youtubeWindowStart(startsOn)||date>=startsOn||date>today
    || status.privacyStatus!=='public'||status.embeddable!==true||length<20*60
    || !(mixTitle.test(title) || (targeted && (targeted.name==='My Analog Journal' || /the\s*lot\s*radio|hÖr|soulection\s+radio/i.test(title))))||notMix.test(title)||spamTitle.test(title)
    || snippet.liveBroadcastContent==='live'||!style || !respected)return;
  const tags=tagsOf(snippet);
  const candidate={
    id:'youtube-'+id,title,creator:targeted?.name??channelTitle,format:'Radio show',
    source:'YouTube · '+(targeted?.name??channelTitle),provider:'YouTube',sourceId:'youtube-mix-'+channelId,
    sourceUrl:'https://www.youtube.com/channel/'+channelId,
    url:'https://www.youtube.com/watch?v='+id,date,dateKind:'published',
    publishedAt:snippet.publishedAt,minutes:length/60,mixKind:'curated-mix',
    mixStyle:style,mixStyleVerified:true,
    verificationStatus:'source-verified',audienceVerified:true,
    viewCount:views,subscriberCount:subscribers,curatorEstablished:known,
    officialVideo:true,videoSourceUrl:'https://www.youtube.com/watch?v='+id,
    embed:{provider:'youtube',id},tags,
  };
  const cover=sourceUrl(snippet.thumbnails?.high?.url??snippet.thumbnails?.medium?.url);
  if(cover && (cover.hostname==='i.ytimg.com'||cover.hostname==='img.youtube.com'))candidate.artwork=cover.href;
  return candidate;
}

export async function collectYouTubeMixes({startsOn,today,profile={},key,fetcher=fetch}={}) {
  if(!key||!isoDate(startsOn)||!isoDate(today))return {items:[],status:'not-configured'};
  const choices=(Array.isArray(profile.explore)?profile.explore:[])
    .filter(x=>typeof x==='string'&&/^[\p{L}\d &-]{3,30}$/u.test(x)
      && genreRules.some(([,re])=>re.test(x)) && !excludesElectronicMix({title:x}) && !/jazz/i.test(x)).slice(0,1);
  const queries=[...targetedMixChannels,...[...youtubeMixQueries,...choices.map(x=>x+' soulful vinyl DJ mix')].map(q=>({q}))];
  const after=youtubeWindowStart(startsOn)+'T00:00:00Z',before=startsOn+'T00:00:00Z';
  const found=new Set(),errors=[];
  const request=async(path,params)=>{
    const response=await fetcher('https://www.googleapis.com/youtube/v3/'+path+'?'+new URLSearchParams(params),
      {signal:AbortSignal.timeout(15000),redirect:'error',headers:{'x-goog-api-key':key}});
    if(!response.ok)throw new Error('YouTube '+path+' '+response.status);
    return response.json();
  };
  for(const {q,channelId} of queries){
    try{
      const data=await request('search',{part:'snippet',type:'video',videoDuration:'long',
        order:'viewCount',maxResults:channelId?'50':'25',publishedAfter:after,publishedBefore:before,...(channelId?{channelId}:{q})});
      if(!Array.isArray(data.items))throw new Error('YouTube search invalid response');
      for(const item of data.items)if(videoId(item.id?.videoId))found.add(item.id.videoId);
    }catch(e){errors.push(String(e.message).slice(0,90));}
  }
  const candidates=[],ids=[...found].slice(0,375),videos=[];
  for(let offset=0;offset<ids.length;offset+=50){
    try{
      const data=await request('videos',{part:'snippet,status,contentDetails,statistics',id:ids.slice(offset,offset+50).join(',')});
      if(!Array.isArray(data.items))throw new Error('YouTube videos invalid response');
      videos.push(...data.items);
    }catch(e){errors.push(String(e.message).slice(0,90));}
  }
  const channels=new Map();
  const channelIds=[...new Set(videos.map(x=>x.snippet?.channelId).filter(channelIdValid))];
  for(let offset=0;offset<channelIds.length;offset+=50){
    try{
      const data=await request('channels',{part:'statistics',id:channelIds.slice(offset,offset+50).join(',')});
      if(!Array.isArray(data.items))throw new Error('YouTube channels invalid response');
      for(const channel of data.items)channels.set(channel.id,channel);
    }catch(e){errors.push(String(e.message).slice(0,90));}
  }
  for(const video of videos){
    const picked=verifiedYouTubeMix(video,startsOn,today,channels.get(video.snippet?.channelId));
    if(picked)candidates.push(picked);
  }
  candidates.sort((a,b)=>Number(b.curatorEstablished)-Number(a.curatorEstablished)
    || b.viewCount-a.viewCount || b.date.localeCompare(a.date));
  return {items:candidates.slice(0,35),status:errors.length?'partial: '+errors.length+' provider request(s) unavailable':'ok',
    found:found.size,eligible:candidates.length,queries:queries.length};
}
